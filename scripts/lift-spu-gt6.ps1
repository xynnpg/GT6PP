# Regenerate the WWS job-manager policy module (image id 5) from EMAIN.elf.
#
# The four embedded SPU ELFs are lifted separately by build_spu_workloads.py.
# This script handles the fifth, raw 0x2F80-byte PM at guest EA 0x013FFE00:
# extract -> find functions -> drop the four WWSJ data words -> lift -> copy
# into gt6/generated/spu_lifted/pm_wwsjob and write the id-5 registry.
#
# Usage: powershell -ExecutionPolicy Bypass -File scripts/lift-spu-gt6.ps1
param(
    [string]$Elf = "",
    [switch]$Force
)

$ErrorActionPreference = "Stop"
$Root = Split-Path -Parent $PSScriptRoot
if (-not $Elf) { $Elf = Join-Path $Root "work\bin\EMAIN.elf" }
$Sdk = Join-Path $Root "third_party\ps3recomp"
$Out = Join-Path $Root "work\spu_analysis\pm_rebuild"
$Lifted = Join-Path $Root "gt6\generated\spu_lifted\pm_wwsjob"
$Registry = Join-Path $Root "gt6\src\gen\spu_workloads_pm.c"

$PmVa = 0x013FFE00
$PmFileOff = 0x13EFE00
$PmSize = 0x2F80
$PmFp = 0x5510DCB89C1E98C2

if (-not (Test-Path $Elf)) { throw "Missing $Elf" }
New-Item -ItemType Directory -Force -Path $Out, $Lifted | Out-Null

Write-Host "[1/5] extract raw WWS PM (VA 0x$($PmVa.ToString('X8')), $PmSize bytes)"
python -c @"
import struct, sys
from pathlib import Path
elf = Path(r'$($Elf -replace '\\','/')')
out = Path(r'$($Out -replace '\\','/')/pm_wwsjob.bin')
data = elf.read_bytes()
pm = data[${PmFileOff}:${PmFileOff}+${PmSize}]
if len(pm) != ${PmSize}:
    sys.exit(f'short read: {len(pm)}')
h = 1469598103934665603
for b in pm:
    h ^= b
    h = (h * 1099511628211) & 0xFFFFFFFFFFFFFFFF
print(f'fingerprint=0x{h:016X} size={len(pm)}')
if h != ${PmFp}:
    sys.exit('fingerprint mismatch')
out.write_bytes(pm)
"@
if ($LASTEXITCODE -ne 0) { exit $LASTEXITCODE }

Write-Host "[2/5] find SPU functions"
python (Join-Path $Sdk "tools\find_spu_functions.py") (Join-Path $Out "pm_wwsjob.bin") `
    --raw --base 0xA00 `
    --code-out (Join-Path $Out "pm_code.bin") `
    --out (Join-Path $Out "pm_functions.json")
if ($LASTEXITCODE -ne 0) { exit $LASTEXITCODE }

Write-Host "[3/5] drop the WWSJ data words (0x1610/0x1620/0x1630/0x1640)"
python -c @"
import json
from pathlib import Path
d = Path(r'$($Out -replace '\\','/')')
f = json.loads((d/'pm_functions.json').read_text())
drop = {0x1610, 0x1620, 0x1630, 0x1640}
def addr(v):
    return int(v, 16) if isinstance(v, str) else int(v)
clean = [x for x in f if addr(x['start']) not in drop]
(d/'pm_functions_clean.json').write_text(json.dumps(clean, indent=1))
print(f'{len(f)} -> {len(clean)} functions')
"@
if ($LASTEXITCODE -ne 0) { exit $LASTEXITCODE }

Write-Host "[4/5] lift 190-function PM"
if ((Test-Path (Join-Path $Lifted "spu_recomp.c")) -and -not $Force) {
    Write-Host "  already present (use -Force to regenerate)"
} else {
    python (Join-Path $Sdk "tools\spu_lifter.py") (Join-Path $Out "pm_code.bin") `
        --base 0xA00 `
        --functions (Join-Path $Out "pm_functions_clean.json") `
        --symbol-prefix pm_clean_ `
        --output $Lifted
    if ($LASTEXITCODE -ne 0) { exit $LASTEXITCODE }
}

Write-Host "[5/5] write id-5 registry"
$registryText = @'
/* WWS job-manager policy module (raw 0x2F80 image at guest 0x013FFE00).
 * GENERATED by scripts/lift-spu-gt6.ps1; do not edit by hand.
 *
 * The runtime fingerprints the raw bytes passed to cellSpursAddWorkload, so
 * the lookup key is FNV-1a-64 0x5510DCB89C1E98C2. Image id 5 does not collide
 * with the four embedded ELF images (ids 1..4). */
#include "spu_workload.h"

extern void spu_begin_image(int image_id);
extern void pm_clean_spu_func_00000A00(spu_context*);
extern void pm_clean_spu_recomp_register(void);

void gt6_spu_register_pm_clean(void)
{
    spu_begin_image(5);
    pm_clean_spu_recomp_register();
    spu_workload_register_img(0x5510DCB89C1E98C2ULL,
                              pm_clean_spu_func_00000A00,
                              5, "pm_wwsjob");
    spu_begin_image(0);
}
'@
Set-Content -Path $Registry -Value $registryText -Encoding ASCII

Write-Host ""
Write-Host "WWS PM ready: $Lifted" -ForegroundColor Green
Write-Host "Registry:    $Registry" -ForegroundColor Green
